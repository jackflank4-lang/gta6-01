// Seeded random numbers for Solmar Bay: every run of the game builds the
// same city, traffic and pedestrians from one seed, so screenshots and
// play-tests are reproducible.
export function hashSeed(text) {
  let h = 5381;
  for (let i = 0; i < text.length; i += 1) {
    h = ((h << 5) + h + text.charCodeAt(i)) >>> 0;
  }
  return h >>> 0;
}

export class Rng {
  constructor(seed) {
    this.state = (seed >>> 0) || 1;
  }

  // SplitMix32: returns a float in [0, 1).
  next() {
    this.state = (this.state + 0x9e3779b9) >>> 0;
    let z = this.state;
    z = Math.imul(z ^ (z >>> 16), 0x21f0aaad);
    z = Math.imul(z ^ (z >>> 15), 0x735a2d97);
    z = (z ^ (z >>> 15)) >>> 0;
    return z / 4294967296;
  }

  range(a, b) {
    return a + (b - a) * this.next();
  }

  int(a, b) {
    return Math.floor(this.range(a, b + 1));
  }

  pick(list) {
    return list[Math.floor(this.next() * list.length)];
  }

  chance(p) {
    return this.next() < p;
  }

  // Roughly normal, mean 0, spread about 1.
  gauss() {
    return (this.next() + this.next() + this.next() - 1.5) * 1.2;
  }

  shuffle(list) {
    for (let i = list.length - 1; i > 0; i -= 1) {
      const j = Math.floor(this.next() * (i + 1));
      const tmp = list[i];
      list[i] = list[j];
      list[j] = tmp;
    }
    return list;
  }
}
